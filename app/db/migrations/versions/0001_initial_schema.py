ORDERS_LIFECYCLE_FUNCTION = """
CREATE FUNCTION orders_enforce_lifecycle() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'created' THEN
            RAISE EXCEPTION 'order % must be inserted in status created, not %', NEW.id, NEW.status
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM audit_events
            WHERE order_id = NEW.id
              AND event_type = 'order_created'
              AND new_state = 'created'
        ) THEN
            RAISE EXCEPTION 'order % has no order_created audit event', NEW.id
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NOT EXISTS (
            SELECT 1 FROM order_transitions
            WHERE from_status = OLD.status AND to_status = NEW.status
        ) THEN
            RAISE EXCEPTION 'order % cannot move from % to %', NEW.id, OLD.status, NEW.status
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM audit_events
            WHERE order_id = NEW.id
              AND event_type = 'order_status_changed'
              AND previous_state = OLD.status
              AND new_state = NEW.status
        ) THEN
            RAISE EXCEPTION 'order % moved from % to % without an audit event',
                NEW.id, OLD.status, NEW.status
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;
    RETURN NULL;
END;
$$
"""


